#!/usr/bin/env node
/**
 * Setup script to inject Firebase config from environment variables
 * Usage: FIREBASE_API_KEY=xxx FIREBASE_PROJECT_ID=xxx node setup-firebase.js
 */

const fs = require('fs');
const path = require('path');

// Read environment variables
const config = {
  apiKey: process.env.FIREBASE_API_KEY || 'YOUR_API_KEY',
  authDomain: process.env.FIREBASE_AUTH_DOMAIN || `${process.env.FIREBASE_PROJECT_ID || 'YOUR_PROJECT_ID'}.firebaseapp.com`,
  databaseURL: process.env.FIREBASE_DATABASE_URL || `https://${process.env.FIREBASE_PROJECT_ID || 'YOUR_PROJECT_ID'}-default-rtdb.firebaseio.com/`,
  projectId: process.env.FIREBASE_PROJECT_ID || 'YOUR_PROJECT_ID',
  storageBucket: process.env.FIREBASE_STORAGE_BUCKET || `${process.env.FIREBASE_PROJECT_ID || 'YOUR_PROJECT_ID'}.appspot.com`,
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID || 'YOUR_MESSAGING_SENDER_ID',
  appId: process.env.FIREBASE_APP_ID || 'YOUR_APP_ID'
};

// Generate the config file
const configContent = `// Firebase configuration - Auto-generated from environment variables
// DO NOT EDIT THIS FILE MANUALLY - Run: node setup-firebase.js

const firebaseConfig = ${JSON.stringify(config, null, 2)};

// Export for use in multiplayer.js
if (typeof module !== 'undefined' && module.exports) {
  module.exports = firebaseConfig;
}
`;

// Write to firebase-config.js
const configPath = path.join(__dirname, 'firebase-config.js');
fs.writeFileSync(configPath, configContent, 'utf8');

console.log('✅ Firebase config generated successfully!');
console.log('📝 Config file: firebase-config.js');
console.log('🔑 API Key:', config.apiKey === 'YOUR_API_KEY' ? 'NOT SET' : config.apiKey.substring(0, 10) + '...');
